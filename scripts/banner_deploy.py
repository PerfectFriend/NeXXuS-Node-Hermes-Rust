import argparse
import json
import subprocess
import sys
import os
from pathlib import Path
from datetime import datetime, timezone


class BannerDeploy:
    def __init__(self, component: str, cycle: int, style: str = "brand", langs: str = "ru,en,zh", readme: bool = True, create_repos: bool = False):
        self.component = component
        self.cycle = cycle
        self.style = style
        self.langs = langs.split(",")
        self.readme = readme
        self.create_repos = create_repos
        self.root = Path("/home/thomas/LivingCode")
        self.artifacts_dir = self.root / "artifacts"
        self.projects_dir = self.root / "projects"

    def run_cmd(self, cmd: str, cwd: Path = None, timeout: int = 600) -> tuple:
        try:
            result = subprocess.run(
                cmd, shell=True, capture_output=True, text=True,
                timeout=timeout, cwd=str(cwd or self.root)
            )
            return result.returncode == 0, result.stdout, result.stderr
        except Exception as e:
            return False, "", str(e)

    def generate_banner_assets(self) -> bool:
        """Generate banner assets for the component"""
        print(f"  ��� Generating {self.style} banner assets for {self.component}...")

        # Create component directory
        comp_dir = self.projects_dir / f"LivingCode-{self.component}-{self.cycle:03d}"
        comp_dir.mkdir(parents=True, exist_ok=True)

        # Create assets directory
        assets_dir = comp_dir / "assets"
        assets_dir.mkdir(parents=True, exist_ok=True)

        # Create placeholder banner files (in real implementation, these would be generated)
        for lang in self.langs:
            banner_file = assets_dir / f"banner_{lang}.png"
            if not banner_file.exists():
                # Create a minimal placeholder
                banner_file.write_text(f"Banner for {self.component} - {lang} - Cycle {self.cycle}", encoding='utf-8')

        print(f"     �� Banner assets created in {assets_dir}")
        return True

    def generate_readme(self) -> bool:
        """Generate README for the component"""
        if not self.readme:
            return True

        print(f"  ��� Generating README for {self.component}...")

        comp_dir = self.projects_dir / f"LivingCode-{self.component}-{self.cycle:03d}"
        readme_file = comp_dir / "README.md"

        readme_content = f"""# LivingCode — {self.component.replace('_', ' ').title()}

**Cycle:** {self.cycle}  
**Style:** {self.style}  
**Languages:** {', '.join(self.langs)}  
**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}

## Overview

This component was auto-deployed by the Living Code Ecosystem banner deployment pipeline.

## Assets

Banner assets are available in the `assets/` directory:
"""
        for lang in self.langs:
            readme_content += f"- `assets/banner_{lang}.png` — {lang.upper()} version\n"

        readme_content += f"""

## Deployment Info

- **Pipeline:** Living Code Ecosystem
- **Cycle:** {self.cycle}
- **Component:** {self.component}
- **Style:** {self.style}
- **Status:** DEPLOYED

---

*Auto-generated by banner_deploy.py*
"""

        readme_file.write_text(readme_content, encoding='utf-8')
        print(f"     �� README created: {readme_file}")
        return True

    def git_init_and_commit(self) -> bool:
        """Initialize git repo and commit"""
        comp_dir = self.projects_dir / f"LivingCode-{self.component}-{self.cycle:03d}"

        print(f"  ��� Initializing git repository...")

        # Initialize git
        success, out, err = self.run_cmd("git init", cwd=comp_dir)
        if not success:
            print(f"     ��� git init failed: {err}")
            return False

        # Configure git user (if not already configured)
        self.run_cmd('git config user.name "LivingCode Bot"', cwd=comp_dir)
        self.run_cmd('git config user.email "bot@livingcode.local"', cwd=comp_dir)

        # Add all files
        success, out, err = self.run_cmd("git add .", cwd=comp_dir)
        if not success:
            print(f"     ��� git add failed: {err}")
            return False

        # Commit
        commit_msg = f"feat: deploy {self.component} banner cycle {self.cycle}"
        success, out, err = self.run_cmd(f'git commit -m "{commit_msg}"', cwd=comp_dir)
        if not success:
            print(f"     ��� git commit failed: {err}")
            return False

        print(f"     �� Git repository initialized and committed")
        return True

    def create_github_repo(self) -> bool:
        """Create private GitHub repository and push"""
        if not self.create_repos:
            print(f"  ������  Skipping GitHub repo creation (--create-repos not set)")
            return True

        comp_dir = self.projects_dir / f"LivingCode-{self.component}-{self.cycle:03d}"
        repo_name = f"LivingCode-{self.component}-{self.cycle:03d}"

        print(f"  ��� Checking/creating private GitHub repository: {repo_name}...")

        # Check if gh CLI is available
        success, out, err = self.run_cmd("gh auth status")
        if not success:
            print(f"     ��� GitHub CLI not authenticated: {err}")
            return False

        # Get GitHub username
        success, username_out, _ = self.run_cmd("gh api user --jq .login")
        if not success:
            print(f"     ��� Failed to get GitHub username: {username_out}")
            return False
        gh_username = username_out.strip()

        # First check if repo already exists
        success, out, err = self.run_cmd(f'gh repo view {repo_name} --json name')
        if success:
            print(f"     ��� Repository already exists, pushing to it...")
            # Add remote if not exists
            remote_url = f"https://github.com/{gh_username}/{repo_name}.git"
            self.run_cmd(f'git remote add origin {remote_url} 2>/dev/null || git remote set-url origin {remote_url}', cwd=comp_dir)
            # Push
            success, out, err = self.run_cmd('git push -u origin main', cwd=comp_dir)
            if not success:
                # Try master branch
                success, out, err = self.run_cmd('git push -u origin master', cwd=comp_dir)
            if not success:
                print(f"     ��� Failed to push: {err}")
                return False
            print(f"     �� Pushed to existing repository: {repo_name}")
            return True

        # Create private repo
        success, out, err = self.run_cmd(f'gh repo create {repo_name} --private --source . --push', cwd=comp_dir)
        if not success:
            print(f"     ��� Failed to create repo: {err}")
            return False

        print(f"     �� Repository created and pushed: {repo_name}")
        return True

    def update_evolution_plan(self) -> bool:
        """Update the evolution plan with deployment info"""
        plan_file = self.root / "EVOLUTION_PLAN.md"

        entry = f"\n- **Cycle {self.cycle}** — {self.component}: Banner deployed ({self.style}, {', '.join(self.langs)}) — {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')}\n"

        if plan_file.exists():
            content = plan_file.read_text(encoding='utf-8')
            # Find the deployment section or append
            if "## Banner Deployments" in content:
                content = content.replace("## Banner Deployments", f"## Banner Deployments{entry}")
            else:
                content += f"\n## Banner Deployments{entry}"
        else:
            content = f"# Evolution Plan\n\n## Banner Deployments{entry}\n"

        plan_file.write_text(content, encoding='utf-8')
        print(f"     �� Evolution plan updated")
        return True

    def write_deploy_report(self, push_success: bool) -> bool:
        """Write deploy report to releases directory for holy_code_deploy_poller"""
        releases_dir = self.root / "releases"
        releases_dir.mkdir(parents=True, exist_ok=True)

        report_file = releases_dir / f"deploy_{self.component}_cycle_{self.cycle:03d}.json"
        report_data = {
            "component": self.component,
            "cycle": self.cycle,
            "style": self.style,
            "langs": self.langs,
            "readme": self.readme,
            "create_repos": self.create_repos,
            "push_success": push_success,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "project_dir": str(self.projects_dir / f"LivingCode-{self.component}-{self.cycle:03d}"),
        }

        report_file.write_text(json.dumps(report_data, indent=2, ensure_ascii=False), encoding='utf-8')
        print(f"     ��� Deploy report written: {report_file}")
        return True

    def deploy(self) -> bool:
        """Run full deployment pipeline"""
        print(f"\n{'='*60}")
        print(f"���� BANNER DEPLOY — {self.component} — Cycle {self.cycle}")
        print(f"Style: {self.style} | Langs: {', '.join(self.langs)} | README: {self.readme} | Create Repos: {self.create_repos}")
        print(f"{'='*60}")

        steps = [
            ("Generate banner assets", self.generate_banner_assets),
            ("Generate README", self.generate_readme),
            ("Initialize git", self.git_init_and_commit),
            ("Create GitHub repo", self.create_github_repo),
            ("Update evolution plan", self.update_evolution_plan),
        ]

        for name, step in steps:
            try:
                if not step():
                    print(f"\n��� FAILED at step: {name}")
                    return False
            except Exception as e:
                print(f"\n��� EXCEPTION at step {name}: {e}")
                return False

        # Write deploy report for holy_code_deploy_poller
        self.write_deploy_report(push_success=self.create_repos)

        print(f"\n{'='*60}")
        print(f"��� BANNER DEPLOY COMPLETE — {self.component}")
        print(f"{'='*60}")
        return True


def main():
    parser = argparse.ArgumentParser(description="Banner Deploy for Living Code Components")
    parser.add_argument("--component", required=True, help="Component name (e.g., boss_fight_system)")
    parser.add_argument("--cycle", type=int, required=True, help="Cycle number")
    parser.add_argument("--style", default="brand", help="Banner style (default: brand)")
    parser.add_argument("--langs", default="ru,en,zh", help="Comma-separated languages (default: ru,en,zh)")
    parser.add_argument("--readme", action="store_true", help="Generate README")
    parser.add_argument("--create-repos", action="store_true", help="Create private GitHub repositories")

    args = parser.parse_args()

    deployer = BannerDeploy(
        component=args.component,
        cycle=args.cycle,
        style=args.style,
        langs=args.langs,
        readme=args.readme,
        create_repos=args.create_repos
    )

    success = deployer.deploy()
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()