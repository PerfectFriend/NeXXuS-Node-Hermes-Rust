import json
import os
import re
import copy
from abc import ABC, abstractmethod
from dataclasses import dataclass, asdict, replace, field
from datetime import datetime
from typing import Any, List, Dict, Optional


@dataclass
class ElementalLife2State:
    """State of project elemental-life-2"""
    cycle: int
    subcycle: int
    status: str
    metrics: Dict[str, float]
    timestamp: str
    change_log: List[str] = field(default_factory=list)
    version: str = field(default="1.0.0")

class EvolutionStrategy(ABC):
    """Abstract base class for evolution strategies."""
   
    @abstractmethod
    def evolve(self, state: ElementalLife2State) -> ElementalLife2State:
        """Evolve the given state and return a new state."""
        pass

class DefaultEvolutionStrategy(EvolutionStrategy):
    """Default evolution strategy that increments cycle and subcycle and updates metrics."""

    def evolve(self, state: ElementalLife2State) -> ElementalLife2State:
        """Default evolution strategy that increments cycle and subcycle and updates metrics."""
        new_state = copy.deepcopy(state)
        new_state.cycle += 1
        new_state.subcycle += 1
        new_state.metrics['evolution_step'] = new_state.subcycle
        new_state.status = "EVOLVED"
        new_state.timestamp = datetime.now().isoformat()
        # Update version based on subcycle
        new_state.version = f"1.0.{new_state.subcycle}"
        # Add a change log entry
        new_state.change_log.append(f"Evolution step {new_state.subcycle} at {new_state.timestamp}")
        return new_state
class ElementalLife2Engine:
    """Engine for project elemental-life-2 - clean architecture, zero bugs"""

    def __init__(self,
                 config: dict | None = None,
                 state: Optional[ElementalLife2State] = None,
                 state_history: Optional[List[ElementalLife2State]] = None,
                 evolution_strategy: Optional[EvolutionStrategy] = None,
                 config_path: str | None = None):
        # Load configuration from file if provided
        if config_path is not None:
            self.config = self.load_config_from_file(config_path)
        elif config is not None:
            self.config = config
        else:
            self.config = {}
            
        if state is not None and state_history is not None:
            self.state = state
            self.state_history = state_history
        else:
            self.state = ElementalLife2State(
                cycle=1,
                subcycle=2,
                status="EVOLVING",
                metrics={},
                timestamp=datetime.now().isoformat()
            )
            self.state_history: List[ElementalLife2State] = []
        self.evolution_strategy = evolution_strategy or DefaultEvolutionStrategy()

    def load_config_from_file(self, filepath: str) -> dict:
        """Load configuration from a JSON file."""
        try:
            with open(filepath, 'r') as f:
                return json.load(f)
        except FileNotFoundError:
            # Return empty dict if file not found
            return {}
        except json.JSONDecodeError:
            # Return empty dict if invalid JSON
            return {}

    def evolve(self) -> dict[str, Any]:
        """One evolution step using the configured strategy."""
        # Цикл 14: замороженный движок не эволюционирует (заморозка была беззубой —
        # freeze() ставил статус, но evolve() молча «оживлял» движок на следующем шаге)
        if self.state.status == "FROZEN":
            return {
                "status": "frozen",
                "subcycle": self.state.subcycle,
                "message": "Engine is FROZEN. Evolve refused; unfreeze (status reset) required."
            }

        # Check for cycle limit and automatic freeze
        max_cycles = self.config.get("max_cycles")
        if max_cycles is not None and self.state.cycle >= max_cycles:
            # Freeze the engine as we've reached or exceeded the cycle limit
            self.state.status = "FROZEN"
            return {
                "status": "frozen",
                "subcycle": self.state.subcycle,
                "message": f"Maximum cycles ({max_cycles}) reached. Engine frozen."
            }

        # PLAN: auto_freeze_threshold — заблаговременная заморозка не позже заданного порога
        # (раньше ключ из конфига вообще не задействовался)
        freeze_threshold = self.config.get("auto_freeze_threshold")
        if freeze_threshold is not None and self.state.cycle >= int(freeze_threshold):
            self.state.status = "FROZEN"
            return {
                "status": "frozen",
                "subcycle": self.state.subcycle,
                "message": f"Auto-freeze threshold ({freeze_threshold}) reached. Engine frozen."
            }
        
        # Save a deep copy of current state to history before evolving
        # (PLAN/audit: replace() was shallow → snapshot shared metrics/change_log with live state)
        self.state_history.append(copy.deepcopy(self.state))

        # Evolve state via strategy
        self.state = self.evolution_strategy.evolve(self.state)

        # Check if evolution caused us to exceed cycle limit (if cycle was incremented)
        max_cycles = self.config.get("max_cycles")
        if max_cycles is not None and self.state.cycle > max_cycles:
            # Freeze the engine as we've exceeded the cycle limit
            self.state.status = "FROZEN"
            return {
                "status": "frozen",
                "subcycle": self.state.subcycle,
                "message": f"Maximum cycles ({max_cycles}) exceeded. Engine frozen."
            }

        # Log the evolution step to file only if logging is enabled (PLAN: улучшение отслеживания состояния)
        if self.config.get("logging_enabled", True):
            # Цикл 13: путь лога берётся из конфига (ключ log_file был мёртвым),
            # дефолт "evolution.log" сохраняет обратную совместимость
            log_path = self.config.get("log_file", "evolution.log")
            log_entry = f"{self.state.timestamp} - Cycle {self.state.cycle}, Subcycle {self.state.subcycle}: Evolution applied\n"
            with open(log_path, "a", encoding="utf-8") as log_file:
                log_file.write(log_entry)

        return {
            "status": "success",
            "subcycle": self.state.subcycle,
            "message": "Evolution applied successfully"
        }

    def verify(self) -> bool:
        """Verify state with enhanced validation"""
        valid_statuses = ["EVOLVING", "EVOLVED", "READY", "FROZEN"]
        if self.state.status not in valid_statuses:
            return False
        
        # Additional validation: cycle and subcycle should be positive integers
        if not isinstance(self.state.cycle, int) or self.state.cycle < 1:
            return False
        if not isinstance(self.state.subcycle, int) or self.state.subcycle < 1:
            return False

        # Metrics should be a dictionary
        if not isinstance(self.state.metrics, dict):
            return False

        # Version should be a non-empty string of the form "major.minor.patch" (PLAN: улучшение проверки состояния)
        if not isinstance(self.state.version, str) or not self.state.version:
            return False
        if not re.fullmatch(r"\d+\.\d+\.\d+", self.state.version):
            return False

        # Change log should be a list of strings
        if not isinstance(self.state.change_log, list):
            return False
        if not all(isinstance(entry, str) for entry in self.state.change_log):
            return False

        return True

    def freeze(self) -> str:
        """Freeze code as ready (FROZEN per protocol)"""
        self.state.status = "FROZEN"
        return f"ElementalLife2 FROZEN at subcycle {self.state.subcycle}"

    def get_state_history(self) -> List[ElementalLife2State]:
        """Return the history of states"""
        return [copy.deepcopy(state) for state in self.state_history]

    def save_state(self, filepath: str) -> None:
        """Save the engine's state (config, current state, and history) to a JSON file.

        Цикл 13: запись атомарна — сначала временный файл <filepath>.tmp,
        затем os.replace поверх старого. Прямая перезапись уничтожала бы
        существующий файл состояния при обрыве записи (диск/процесс).
        """
        data_to_save = {
            "config": self.config,
            "state": asdict(self.state),
            "state_history": [asdict(s) for s in self.state_history]
        }
        tmp_path = filepath + ".tmp"
        try:
            with open(tmp_path, 'w') as f:
                json.dump(data_to_save, f, indent=2)
            os.replace(tmp_path, filepath)  # атомарная замена в рамках одной ФС
        except BaseException:
            # не оставляем мусорный .tmp при любом падении (сериализация, диск, KeyboardInterrupt)
            try:
                os.remove(tmp_path)
            except OSError:
                pass
            raise

    @classmethod
    def load_state(cls, filepath: str) -> 'ElementalLife2Engine':
        """Load an engine's state from a JSON file and return a new engine instance."""
        with open(filepath, 'r') as f:
            data = json.load(f)
        
        config = data.get("config", {})
        state_dict = data.get("state")
        state_history_list = data.get("state_history", [])

        if state_dict is None:
            # If no state in file, create a default one (should not happen if file was saved by us)
            state = ElementalLife2State(
                cycle=1,
                subcycle=2,
                status="EVOLVING",
                metrics={},
                timestamp=datetime.now().isoformat()
            )
            state_history = []
        else:
            state = ElementalLife2State(**state_dict)
            state_history = [ElementalLife2State(**s) for s in state_history_list]

        return cls(config=config, state=state, state_history=state_history)
    
    def reset(self) -> str:
        """Reset the engine to initial state."""
        self.state = ElementalLife2State(
            cycle=1,
            subcycle=2,
            status="EVOLVING",
            metrics={},
            timestamp=datetime.now().isoformat()
        )
        self.state_history.clear()
        return "ElementalLife2 engine reset to initial state"