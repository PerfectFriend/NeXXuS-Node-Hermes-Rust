# HOT
import sys
with open('lord_of_code.py', 'r') as f:
    lines = f.readlines()

# Find the start and end of the block to replace
start = None
for i, line in enumerate(lines):
    if line.strip().startswith("f.write(f'# Lord Report - {date_str}"):
        start = i
        break

if start is not None:
    # We'll replace 7 lines (from start to start+6)
    new_lines = [
        "        f.write(f'# Lord Report - {date_str}\\n\\n')\n",
        "        f.write(f'Triggered by: [TRIGGER_LORD] {project}\\n')\n",
        "        f.write(f'Project: {project}\\n')\n",
        "        f.write(f'Reviewed hot code in {project_path}\\n')\n",
        "        f.write(f'Marked hot/cold as needed (simplified).\\n')\n",
        "        f.write(f'\\n---\\n')\n",
        "        f.write('Report generated by Lord Agent.\\n')\n"
    ]
    # Replace the lines
    lines[start:start+7] = new_lines

with open('lord_of_code.py', 'w') as f:
    f.writelines(lines)
